// Generates deterministic font metrics + font manifests from the @fontsource files.
//   src/og/core/fonts.ts      portable font manifest (CDN urls) + metrics, used by every renderer
//   src/lib/font-urls.ts      site-only: Vite ?url imports of the woff2 files
// Run: node scripts/build-metrics.mjs
import * as fontkit from 'fontkit'
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')

/** family name used in SVG/CSS -> fontsource slug + faces */
const FAMILIES = [
  ['Instrument Serif', 'instrument-serif', ['400n', '400i'], 'serif'],
  ['Fraunces', 'fraunces', ['300n', '300i', '600n', '900n'], 'serif'],
  ['Newsreader', 'newsreader', ['400n', '400i', '600n'], 'serif'],
  ['Bodoni Moda', 'bodoni-moda', ['500n', '500i', '800n'], 'serif'],
  ['UnifrakturMaguntia', 'unifrakturmaguntia', ['400n'], 'display'],
  ['Cormorant Garamond', 'cormorant-garamond', ['400n', '400i', '600n', '600i'], 'serif'],
  ['Inter Tight', 'inter-tight', ['400n', '500n', '600n', '800n'], 'sans'],
  ['Geist', 'geist-sans', ['400n', '500n', '600n', '700n'], 'sans'],
  ['Hanken Grotesk', 'hanken-grotesk', ['400n', '500n', '700n'], 'sans'],
  ['Space Grotesk', 'space-grotesk', ['400n', '500n', '700n'], 'sans'],
  ['Bricolage Grotesque', 'bricolage-grotesque', ['400n', '600n', '800n'], 'sans'],
  ['Syne', 'syne', ['500n', '700n', '800n'], 'display'],
  ['Unbounded', 'unbounded', ['400n', '600n', '800n'], 'display'],
  ['Anton', 'anton', ['400n'], 'display'],
  ['Big Shoulders Display', 'big-shoulders-display', ['600n', '900n'], 'display'],
  ['Silkscreen', 'silkscreen', ['400n', '700n'], 'display'],
  ['JetBrains Mono', 'jetbrains-mono', ['400n', '500n', '700n'], 'mono'],
  ['IBM Plex Mono', 'ibm-plex-mono', ['400n', '500n', '600n'], 'mono'],
  ['Geist Mono', 'geist-mono', ['400n', '500n'], 'mono'],
]

const CHARS = []
for (let c = 32; c <= 126; c++) CHARS.push(c)
for (let c = 160; c <= 255; c++) CHARS.push(c)
const EXTRA = '‘’“”–—…•·›‹€™→←↗★✦№'
for (const ch of EXTRA) CHARS.push(ch.codePointAt(0))

const metrics = {}
const faces = []
for (const [family, slug, list, kind] of FAMILIES) {
  for (const f of list) {
    const weight = Number(f.slice(0, -1))
    const style = f.endsWith('i') ? 'italic' : 'normal'
    const file = `${slug}-latin-${weight}-${style}.woff2`
    const abs = path.join(ROOT, 'node_modules/@fontsource', slug, 'files', file)
    if (!fs.existsSync(abs)) throw new Error('missing ' + abs)
    const font = fontkit.create(fs.readFileSync(abs))
    const upm = font.unitsPerEm
    const adv = CHARS.map((cp) => {
      if (!font.hasGlyphForCodePoint(cp)) return -1
      return Math.round((font.glyphForCodePoint(cp).advanceWidth / upm) * 1000)
    })
    const key = `${family}|${weight}|${style}`
    metrics[key] = {
      a: adv,
      asc: Math.round((font.ascent / upm) * 1000),
      dsc: Math.round((font.descent / upm) * 1000),
      cap: Math.round(((font.capHeight || font.ascent * 0.7) / upm) * 1000),
      xh: Math.round(((font.xHeight || font.ascent * 0.5) / upm) * 1000),
    }
    faces.push({ family, slug, weight, style, kind, file })
  }
}

const header = '// AUTO-GENERATED by scripts/build-metrics.mjs — do not edit by hand.\n'

const fontsTs = `${header}
export type FontStyle = 'normal' | 'italic'
export type FontKind = 'serif' | 'sans' | 'mono' | 'display'

export interface FontFaceDef {
  family: string
  /** @fontsource package slug */
  slug: string
  weight: number
  style: FontStyle
  kind: FontKind
}

/** All font faces opengraphcn templates can use. Every face is OFL-licensed and published by Fontsource. */
export const FONT_FACES: FontFaceDef[] = ${JSON.stringify(
  faces.map(({ family, slug, weight, style, kind }) => ({ family, slug, weight, style, kind })),
)}

/** CDN url for a face. format: 'woff2' for browsers, 'ttf' for server renderers (resvg / fontkit). */
export function fontUrl(face: Pick<FontFaceDef, 'slug' | 'weight' | 'style'>, format: 'woff2' | 'ttf' = 'woff2') {
  return \`https://cdn.jsdelivr.net/fontsource/fonts/\${face.slug}@latest/latin-\${face.weight}-\${face.style}.\${format}\`
}

/** codepoints covered by the metric tables, in order */
export const METRIC_CHARS: number[] = ${JSON.stringify(CHARS)}

/** advance widths in 1/1000 em (-1 = glyph missing), plus vertical metrics */
export const FONT_METRICS: Record<string, { a: number[]; asc: number; dsc: number; cap: number; xh: number }> = ${JSON.stringify(metrics)}
`
fs.writeFileSync(path.join(ROOT, 'src/og/core/fonts.ts'), fontsTs)

const urlsTs =
  header +
  faces.map((f, i) => `import f${i} from '@fontsource/${f.slug}/files/${f.file}?url'`).join('\n') +
  `\n\n/** key: "Family|weight|style" -> bundled woff2 url */\nexport const FONT_URLS: Record<string, string> = {\n` +
  faces.map((f, i) => `  ${JSON.stringify(`${f.family}|${f.weight}|${f.style}`)}: f${i},`).join('\n') +
  '\n}\n'
fs.writeFileSync(path.join(ROOT, 'src/lib/font-urls.ts'), urlsTs)

console.log(`wrote metrics for ${faces.length} faces`)
