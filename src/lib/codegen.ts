import { DEFAULT_OPTIONS, type OgConfig } from '../og/core/types'
import { getTemplate } from '../og/templates'
import { REGISTRY_URL, SITE_URL } from './site'

// Source generators for the Export panel. Output targets the installable registry modules,
// so generated code is real, compiles, and renders identically to the Studio.

export const componentName = (id: string) => id.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('') + 'Image'
/** source file name of a template ("index" would collide with templates/index.ts) */
export const templateFile = (id: string) => (id === 'index' ? 'index-catalog' : id)
export const templateVar = (id: string) => id.replace(/-(\w)/g, (_, c: string) => c.toUpperCase())

function literal(value: unknown, indent = 2): string {
  const pad = ' '.repeat(indent)
  if (value === null) return 'null'
  if (Array.isArray(value)) return `[${value.map((v) => literal(v, indent)).join(', ')}]`
  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>).filter(([, v]) => v !== undefined && v !== '')
    if (!entries.length) return '{}'
    return `{\n${entries.map(([k, v]) => `${pad}  ${/^[a-zA-Z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${literal(v, indent + 2)},`).join('\n')}\n${pad}}`
  }
  return JSON.stringify(value)
}

/** props for the template component, with uploaded images swapped for file paths */
export function propsFor(cfg: OgConfig) {
  const notes: string[] = []
  const assets: Record<string, string> = {}
  for (const [k, v] of Object.entries(cfg.assets)) {
    if (!v) continue
    if (v.startsWith('data:')) {
      const ext = /^data:image\/(png|jpe?g|webp|svg\+xml|gif)/.exec(v)?.[1]?.replace('svg+xml', 'svg').replace('jpeg', 'jpg') ?? 'png'
      assets[k] = `/og/${k}.${ext}`
      notes.push(`Save your uploaded ${k} as public/og/${k}.${ext}`)
    } else assets[k] = v
  }
  const options: Record<string, unknown> = {}
  for (const [k, v] of Object.entries(cfg.options)) if (v !== undefined && v !== (DEFAULT_OPTIONS as unknown as Record<string, unknown>)[k]) options[k] = v
  const content = Object.fromEntries(Object.entries(cfg.content).filter(([, v]) => v !== undefined && v !== null && v !== ''))
  const theme = Object.fromEntries(Object.entries(cfg.theme).filter(([, v]) => v))
  return { content, theme, options, assets, notes }
}

function propsBlock(cfg: OgConfig, indent: number) {
  const p = propsFor(cfg)
  const pad = ' '.repeat(indent)
  const lines = [`${pad}content={${literal(p.content, indent)}}`]
  if (Object.keys(p.theme).length) lines.push(`${pad}theme={${literal(p.theme, indent)}}`)
  if (Object.keys(p.options).length) lines.push(`${pad}options={${literal(p.options, indent)}}`)
  if (Object.keys(p.assets).length) lines.push(`${pad}assets={${literal(p.assets, indent)}}`)
  return { text: lines.join('\n'), notes: p.notes }
}

export function reactSource(cfg: OgConfig) {
  const t = getTemplate(cfg.template)
  const comp = componentName(t.id)
  const name = (cfg.content.name || 'Project').replace(/[^a-zA-Z0-9]/g, '') || 'Project'
  const { text, notes } = propsBlock(cfg, 6)
  return `// ${t.name} — generated by opengraphcn (${SITE_URL})
// Install the template once:
//   npx shadcn@latest add ${REGISTRY_URL}/${t.id}.json
${notes.map((n) => `// ${n}`).join('\n')}${notes.length ? '\n' : ''}import { ${comp} } from '@/components/opengraphcn/templates/${templateFile(t.id)}'

/** Renders the ${t.name} card as a responsive 1200×630 SVG. */
export function ${name}OgImage({ className }: { className?: string }) {
  return (
    <${comp}
      className={className}
${text}
    />
  )
}
`
}

export function nextSource(cfg: OgConfig) {
  const t = getTemplate(cfg.template)
  const v = templateVar(t.id)
  const p = propsFor(cfg)
  const alt = `${cfg.content.name} — ${cfg.content.headline}`.replace(/'/g, "\\'")
  const obj: Record<string, unknown> = { content: p.content }
  if (Object.keys(p.theme).length) obj.theme = p.theme
  if (Object.keys(p.options).length) obj.options = p.options
  if (Object.keys(p.assets).length) obj.assets = Object.fromEntries(Object.entries(p.assets).map(([k, a]) => [k, a.startsWith('/') ? `\${origin}${a}` : a]))
  let body = literal(obj, 2)
  body = body.replace(/"\$\{origin\}([^"]*)"/g, '`${origin}$1`')
  return `// app/opengraph-image.tsx — generated by opengraphcn (${SITE_URL})
//
// 1. Install the template and the server renderer:
//      npx shadcn@latest add ${REGISTRY_URL}/${t.id}.json ${REGISTRY_URL}/server.json
// 2. Keep the renderer packages out of the bundle (next.config.ts):
//      serverExternalPackages: ['@resvg/resvg-js', 'fontkit']
//
// Why not next/og? Satori cannot render SVG <text>, filters or patterns. opengraphcn renders the
// exact same SVG as the Studio, outlines the text with fontkit and rasterizes it with resvg.
${p.notes.map((n) => `// ${n}`).join('\n')}${p.notes.length ? '\n' : ''}import { ${v} } from '@/components/opengraphcn/templates/${templateFile(t.id)}'
import { renderOgPng } from '@/components/opengraphcn/server/render'

export const runtime = 'nodejs'
export const alt = '${alt}'
export const size = { width: 1200, height: 630 }
export const contentType = 'image/png'
${p.assets && Object.values(p.assets).some((a) => a.startsWith('/')) ? `\nconst origin = process.env.NEXT_PUBLIC_SITE_URL ?? 'http://localhost:3000'\n` : ''}
export default async function Image() {
  const png = await renderOgPng(${v}, ${body})
  return new Response(png, { headers: { 'Content-Type': 'image/png', 'Cache-Control': 'public, max-age=31536000, immutable' } })
}
`
}

export function jsonSource(cfg: OgConfig) {
  return JSON.stringify({ $schema: `${SITE_URL}/schema/config.json`, generator: 'opengraphcn', ...cfg }, null, 2)
}

export function fileBase(cfg: OgConfig) {
  return `${(cfg.content.name || 'og').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'og'}-${cfg.template}`
}
